"""Intake: register a recording, with a rights statement and a source credit.

Baitreel only takes local files. It has no way to download a recording from a
link, on purpose: recordings belong to the people who made them.
"""

from __future__ import annotations

import hashlib
import re
from datetime import UTC, datetime
from pathlib import Path

from . import audio, workspace
from .models import Bait, Rights, SourceKind

RIGHTS_STATEMENT = (
    "I made this recording, or I have its creator's permission to use it, "
    "and I may publish educational clips made from it."
)
DEMO_STATEMENT = (
    "This is a scripted demo call generated by Baitreel with synthetic voices. "
    "No real person or real call is involved."
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "bait"


def register(
    recording: Path,
    credit: str,
    attested_by: str,
    kind: SourceKind = "real",
    title: str | None = None,
) -> Bait:
    """Create (or reload) the working folder for a recording."""
    recording = recording.expanduser().resolve()
    if not recording.is_file():
        raise FileNotFoundError(f"No recording at {recording}")
    if not credit.strip():
        raise ValueError("A source credit is required. It is shown on every clip.")
    if not attested_by.strip():
        raise ValueError("A rights statement must be made by a named person.")

    sha = _sha256(recording)
    bait_id = f"{_slug(recording.stem)}-{sha[:8]}"
    path = workspace.bait_dir(bait_id) / "bait.json"
    if path.exists():
        return workspace.load(path, Bait)

    now = datetime.now(UTC)
    bait = Bait(
        id=bait_id,
        title=title or recording.stem,
        kind=kind,
        credit=credit.strip(),
        source_path=str(recording),
        source_name=recording.name,
        source_sha256=sha,
        duration=audio.probe_duration(recording),
        rights=Rights(
            attested_by=attested_by.strip(),
            statement=DEMO_STATEMENT if kind == "scripted-demo" else RIGHTS_STATEMENT,
            attested_at=now,
        ),
        created_at=now,
    )
    workspace.save(path, bait)
    return bait
